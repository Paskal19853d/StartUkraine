-- ============================================================
-- Модуль "Друзі та партнери": окреме посилання для підпису
-- Виконати на ПРОДІ через PhpMyAdmin: база zoryana_pamyat -> SQL
--
-- Раніше підпис (caption) виводився лише як текст (не клікабельний).
-- Тепер підпис може мати ВЛАСНЕ посилання (caption_url), незалежне
-- від посилання картинки (link_url) — різні партнери можуть вести
-- на різні URL для картинки і для тексту підпису.
--
-- Якщо caption_url порожній — підпис автоматично успадковує link_url
-- картинки (зворотна сумісність, дивись index.html renderPartners()).
-- Якщо код (Paskal.py) уже перезапущено на проді, ця колонка могла
-- створитись автоматично через ALTER TABLE в init_db() — цей запит
-- безпечно виконати повторно, IF NOT EXISTS проігнорує дубль.
-- ============================================================

ALTER TABLE partners ADD COLUMN IF NOT EXISTS caption_url VARCHAR(500) NOT NULL DEFAULT '';

-- Виправлення партнера "Українська Діаспора" — посилання було
-- помилково вставлено HTML-тегом прямо в caption (де воно екранується).
UPDATE partners
SET
  link_url    = '/ud.html',
  caption     = 'Підтримати - Зробити внесок',
  caption_url = '/ud.html'
WHERE name = 'Українська Діаспора';
